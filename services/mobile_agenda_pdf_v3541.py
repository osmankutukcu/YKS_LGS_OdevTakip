def _find_font_pair():
    """Use a local font already installed with the OS/application (no shipped font)."""
    candidates = []
    if os.name == 'nt':
        root = Path(os.environ.get('WINDIR', r'C:\Windows')) / 'Fonts'
        candidates.extend([(root / 'arial.ttf', root / 'arialbd.ttf'),
                           (root / 'segoeui.ttf', root / 'segoeuib.ttf')])
    if os.sys.platform == 'darwin':
        candidates.extend([
            (Path('/System/Library/Fonts/Supplemental/Arial.ttf'),
             Path('/System/Library/Fonts/Supplemental/Arial Bold.ttf')),
            (Path('/Library/Fonts/Arial.ttf'), Path('/Library/Fonts/Arial Bold.ttf')),
        ])
    candidates.append((Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'),
                       Path('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf')))
    try:
        import matplotlib
        p = Path(matplotlib.get_data_path()) / 'fonts' / 'ttf'
        candidates.append((p / 'DejaVuSans.ttf', p / 'DejaVuSans-Bold.ttf'))
    except (ImportError, AttributeError, OSError):
        pass
    for regular, bold in candidates:
        if regular.is_file():
            return str(regular), str(bold if bold.is_file() else regular)
    raise RuntimeError('Türkçe karakterleri destekleyen PDF yazı tipi bulunamadı.')


def _setup_font():
    if 'AgendaTR' not in pdfmetrics.getRegisteredFontNames():
        regular, bold = _find_font_pair()
        pdfmetrics.registerFont(TTFont('AgendaTR', regular))
        pdfmetrics.registerFont(TTFont('AgendaTRBold', bold))
    return 'AgendaTR', 'AgendaTRBold'


def normalize_mobile_number(raw):
    """Normalize common TR student/parent numbers and safe international E.164.

    Return ASCII digits for wa.me, or None for ambiguous/invalid input.
    """
    raw = '' if raw is None else str(raw).strip()
    if not raw or re.search(r'[^0-9+().\s-]', raw):
        return None
    # Do not silently turn annotations such as 'veli 905xx...' into a phone
    # number. Only formatting punctuation, digits and a leading '+' are valid.
    if raw.count('+') > 1 or ('+' in raw and not raw.lstrip().startswith('+')):
        return None
    digits = re.sub(r'\D', '', raw)
    if digits.startswith('00'):
        digits = digits[2:]
    if len(digits) == 10:
        if not digits.startswith('5'):
            return None  # Unqualified local numbers would be ambiguous.
        digits = '90' + digits
    elif len(digits) == 11 and digits.startswith('05'):
        digits = '90' + digits[1:]
    if not 10 <= len(digits) <= 15 or digits[0] == '0' or set(digits) == {'0'}:
        return None
    return digits


def whatsapp_url(phone, message):
    number = normalize_mobile_number(phone)
    if not number:
        return None
    # quote explicitly preserves newlines / Turkish text in a robust URI.
    return 'https://wa.me/' + number + '?text=' + urllib.parse.quote(str(message), safe='')



# V3.5.43: iOS, Android and PDF viewers may reject very long wa.me links.
# Split only the outgoing draft URI; do not edit the source homework or the
# existing text generated by the teacher's WhatsApp message builders.
MAX_WHATSAPP_URL_LENGTH = 1800


def whatsapp_message_parts(message, *, max_url_length=MAX_WHATSAPP_URL_LENGTH):
    """Return WhatsApp draft texts, each safe to encode in a bounded URL.

    The original message is preserved exactly when one part suffices. Larger
    messages are split at line boundaries where possible, then by character
    (without losing a single character). Each section receives a numbered
    heading to make manual sequential sending understandable on a phone.
    This only opens drafts. It never sends a WhatsApp message.
    """
    text = '' if message is None else str(message)
    if max_url_length < 160:
        raise ValueError('WhatsApp bağlantı sınırı çok küçük.')
    uri_prefix = 'https://wa.me/' + '9' * 15 + '?text='
    overhead = len(uri_prefix) + len(urllib.parse.quote('Bölüm 999/999\n', safe=''))
    capacity = max_url_length - overhead
    if capacity < 64:
        raise ValueError('WhatsApp bağlantı sınırı içerik için yetersiz.')
    if len(uri_prefix) + len(urllib.parse.quote(text, safe='')) <= max_url_length:
        return [text]

    # Keep newlines intact so each original homework entry appears exactly
    # once when the numbered payloads are joined without their headings.
    chunks = []
    current = ''
    current_len = 0
    for line in text.splitlines(keepends=True):
        line_len = len(urllib.parse.quote(line, safe=''))
        if current and current_len + line_len > capacity:
            chunks.append(current)
            current, current_len = '', 0
        if line_len <= capacity:
            current += line
            current_len += line_len
            continue
        for char in line:
            char_len = len(urllib.parse.quote(char, safe=''))
            if current and current_len + char_len > capacity:
                chunks.append(current)
                current, current_len = '', 0
            if char_len > capacity:
                raise ValueError('WhatsApp mesajı güvenli şekilde bölünemiyor.')
            current += char
            current_len += char_len
    if current:
        chunks.append(current)

    if len(chunks) > 999:
        raise ValueError('WhatsApp mesajı çok fazla bölüme ayrılıyor.')
    total = len(chunks)
    result = [f'Bölüm {index}/{total}\n{part}' for index, part in enumerate(chunks, 1)]
    # Conservative length bound including the full URL and UTF-8 escapes.
    if any(len(uri_prefix) + len(urllib.parse.quote(x, safe='')) > max_url_length
           for x in result):
        raise ValueError('WhatsApp bağlantısı güvenli uzunluk sınırını aşıyor.')
    return result


def whatsapp_actions(phone, message, *, single_label, multi_label):
    """Return action tuples (label, PDF color, URL), with full text preserved."""
    normalized = normalize_mobile_number(phone)
    if not normalized:
        return []
    parts = whatsapp_message_parts(message)
    if len(parts) == 1:
        return [(single_label, '#16a34a', whatsapp_url(normalized, parts[0]))]
    return [(f'{multi_label} {idx}/{len(parts)}', '#16a34a',
             whatsapp_url(normalized, payload))
            for idx, payload in enumerate(parts, 1)]


def call_url(phone):
    number = normalize_mobile_number(phone)
    return 'tel:+' + number if number else None


def _safe(value):
    return escape('' if value is None else str(value))


class LinkButtons(Flowable):
    """Visible PDF action chips with explicit /URI annotations for all viewers."""
    def __init__(self, actions, font='AgendaTRBold'):
        super().__init__()
        self.actions = [a for a in actions if a[2]]
        self.font = font
        self._positions = []

    def wrap(self, availWidth, availHeight):
        self.width = availWidth
        self._positions = []
        x = 0
        y_row = 0
        h = 26
        for label, bg, uri in self.actions:
            w = min(availWidth, max(60, pdfmetrics.stringWidth(label, self.font, 9) + 25))
            if x and x + w > availWidth:
                x = 0
                y_row += 1
            self._positions.append((x, y_row, w, h, label, bg, uri))
            x += w + 8
        self.height = (max((r[1] for r in self._positions), default=-1) + 1) * 34
        return self.width, self.height

    def draw(self):
        canv = self.canv
        for x, row, w, h, label, bg, uri in self._positions:
            y = self.height - row * 34 - h - 1
            canv.setStrokeColor(LINE if bg == '#ffffff' else colors.HexColor(bg))
            canv.setFillColor(colors.HexColor(bg))
            canv.roundRect(x, y, w, h, 5, fill=1, stroke=1)
            canv.setFillColor(TEXT if bg == '#ffffff' else colors.white)
            canv.setFont(self.font, 9)
            canv.drawCentredString(x + w / 2, y + 8, label)
            canv.linkURL(uri, rect=(x, y, x + w, y + h), relative=1, thickness=0)


# V3.5.42: Native PDF GoTo links and outline destinations are intentionally
# independent of HTML/Javascript. They work offline and require no web server.
class AgendaBookmark(Flowable):
    def __init__(self, key, label=None):
        super().__init__()
        self.key, self.label = key, label

    def wrap(self, availWidth, availHeight):
        self.width, self.height = 0, 0
        return 0, 0

    def draw(self):
        self.canv.bookmarkHorizontal(self.key, 0, 0)
        if self.label:
            self.canv.addOutlineEntry(self.label, self.key, level=0, closed=False)


class AgendaDayIndex(Flowable):
    """Thumb-friendly, 2-column week index with PDF-native internal links."""
    def __init__(self, rows, font='AgendaTR', bold='AgendaTRBold'):
        super().__init__()
        self.rows = rows  # (key, date text, day name, homework count, meeting count)
        self.font, self.bold = font, bold

    def wrap(self, availWidth, availHeight):
        self.width = availWidth
        self.height = 26 + ((len(self.rows) + 1) // 2) * 43 + 5
        return self.width, self.height

    def draw(self):
        c = self.canv
        c.setFont(self.bold, 10)
        c.setFillColor(TEXT)
        c.drawString(0, self.height - 13, 'HAFTALIK HIZLI ERİŞİM')
        box_width = (self.width - 10) / 2
        for i, (key, day_date, day_name, homework, meetings) in enumerate(self.rows):
            col, row = i % 2, i // 2
            x = col * (box_width + 10)
            y = self.height - 24 - (row + 1) * 43
            c.setFillColor(colors.HexColor('#f3f7ff'))
            c.setStrokeColor(LINE)
            c.roundRect(x, y, box_width, 36, 6, fill=1, stroke=1)
            c.setFillColor(BLUE)
            c.setFont(self.bold, 9)
            c.drawString(x + 9, y + 21, f'{day_name}  {day_date}')
            c.setFillColor(MUTED)
            c.setFont(self.font, 8)
            c.drawString(x + 9, y + 8, f'{homework} ödev  ·  {meetings} görüşme')
            # Named PDF GoTo destination works without network connectivity.
            c.linkRect('', key, Rect=(x, y, x + box_width, y + 36), relative=1, thickness=0)



# V3.5.44: The directory is an optional, PDF-native navigation aid.  Identity
# is never inferred from a student's name or telephone number.
def _student_directory(schedule, next_7_days):
    """Return ordered entries and per-event first-occurrence bookmark targets.

    The stable student ID is used for deduplication when available. Events
    without an ID receive separate entries rather than being merged by name.
    Nothing from this function is written back to the database or schedule.
    """
    entries = []
    positions = {}
    seen = {}
    for di, (_date, day_name) in enumerate(next_7_days):
        for ei, event in enumerate(schedule.get(day_name, ()) or ()):
            raw_oid = event.get('oid')
            has_id = raw_oid is not None and str(raw_oid).strip() != ''
            identity = ('oid', str(raw_oid)) if has_id else ('event', di, ei)
            if identity not in seen:
                key = f'student_{len(entries)+1}'
                entry = {
                    'key': key,
                    'name': str(event.get('ad') or 'Adı belirtilmemiş öğrenci'),
                    'oid': str(raw_oid) if has_id else None,
                    'day': str(day_name),
                    'count': 0,
                }
                seen[identity] = entry
                entries.append(entry)
                positions[(di, ei)] = key
            seen[identity]['count'] += 1
    name_counts = {}
    for entry in entries:
        name_counts[entry['name'].casefold()] = name_counts.get(entry['name'].casefold(), 0) + 1
    for entry in entries:
        if name_counts[entry['name'].casefold()] > 1:
            # Make two students with identical names distinguishable. There
            # is no guess based on a matching phone or name.
            prefix = f'No {entry["oid"]} · ' if entry['oid'] else f'Kimlik yok {entry["key"].rsplit("_", 1)[-1]} · '
            entry['label'] = prefix + entry['name']
        else:
            entry['label'] = entry['name']
    # Turkish alphabet sorting is display-only and does not affect identity.
    def sort_key(item):
        folded = item['name'].casefold().translate(str.maketrans({'ı': 'i', 'ğ': 'g', 'ş': 's', 'ç': 'c', 'ö': 'o', 'ü': 'u'}))
        return (folded, item['oid'] or '', item['key'])
    return sorted(entries, key=sort_key), positions


def _fit_label(label, font, font_size, max_width):
    """Trim only the *display*, never the actual PDF destination or data."""
    if pdfmetrics.stringWidth(label, font, font_size) <= max_width:
        return label
    ellipsis = '…'
    remaining = max_width - pdfmetrics.stringWidth(ellipsis, font, font_size)
    if remaining <= 0:
        return ellipsis
    while label and pdfmetrics.stringWidth(label, font, font_size) > remaining:
        label = label[:-1]
    return label.rstrip() + ellipsis


class AgendaStudentIndex(Flowable):
    """A compact, paginated two-column student directory for PDF/mobile."""
    def __init__(self, entries, *, continuation=False, font='AgendaTR', bold='AgendaTRBold'):
        super().__init__()
        self.entries = entries
        self.continuation = continuation
        self.font, self.bold = font, bold

    def wrap(self, availWidth, availHeight):
        self.width = availWidth
        self.height = 31 + ((len(self.entries) + 1) // 2) * 40
        return self.width, self.height

    def draw(self):
        c = self.canv
        c.setFillColor(TEXT)
        c.setFont(self.bold, 10)
        heading = 'ÖĞRENCİ HIZLI ERİŞİM' if not self.continuation else 'ÖĞRENCİ DİZİNİ · DEVAM'
        c.drawString(0, self.height - 13, heading)
        width = (self.width - 10) / 2
        for i, entry in enumerate(self.entries):
            col, row = i % 2, i // 2
            x = col * (width + 10)
            y = self.height - 31 - (row + 1) * 40
            c.setFillColor(colors.HexColor('#f8fafc'))
            c.setStrokeColor(LINE)
            c.roundRect(x, y, width, 35, 5, stroke=1, fill=1)
            c.setFillColor(TEXT)
            c.setFont(self.bold, 8.5)
            title = _fit_label(entry['label'], self.bold, 8.5, width - 14)
            c.drawString(x + 7, y + 20, title)
            c.setFont(self.font, 7.3)
            c.setFillColor(MUTED)
            summary = f'{entry["day"]} · {entry["count"]} kayıt'
            c.drawString(x + 7, y + 8, _fit_label(summary, self.font, 7.3, width - 14))
            c.linkRect('', entry['key'], Rect=(x, y, x + width, y + 35),
                       relative=1, thickness=0)

def _styles(font, bold):
    return {
        'title': ParagraphStyle('agTitle', fontName=bold, fontSize=16, leading=21,
                                textColor=colors.white, alignment=TA_CENTER),
        'sub': ParagraphStyle('agSubtitle', fontName=font, fontSize=9, leading=13,
                              textColor=colors.HexColor('#d7e5ff'), alignment=TA_CENTER),
        'day': ParagraphStyle('agDay', fontName=bold, fontSize=12, leading=16,
                              textColor=colors.white),
        'student': ParagraphStyle('agStudent', fontName=bold, fontSize=11.5,
                                  leading=16, textColor=TEXT),
        'badge': ParagraphStyle('agBadge', fontName=bold, fontSize=8.5,
                                leading=12, textColor=colors.HexColor('#b91c1c')),
        'body': ParagraphStyle('agBody', fontName=font, fontSize=9.2, leading=14,
                               textColor=TEXT, alignment=TA_LEFT),
        'muted': ParagraphStyle('agMuted', fontName=font, fontSize=8.3, leading=12,
                                textColor=MUTED),
        'note': ParagraphStyle('agNote', fontName=font, fontSize=8.5, leading=12,
                               textColor=colors.HexColor('#73520a')),
    }


def _footer(canvas, doc, font, *, has_student_directory=False):
    canvas.saveState()
    canvas.setStrokeColor(LINE)
    canvas.line(36, 37, A4[0] - 36, 37)
    canvas.setFont(font, 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(36, 25, 'KoçPilot 360 • Haftalık Cep Ajandası')
    canvas.drawRightString(A4[0] - 36, 25, f'Sayfa {doc.page}')
    if doc.page > 1:
        canvas.setFillColor(BLUE)
        canvas.drawCentredString(A4[0] / 2, 25, 'HAFTAYA DÖN')
        canvas.linkRect('', 'agenda_start', Rect=(A4[0]/2-52, 18, A4[0]/2+52, 34), relative=0, thickness=0)
        if has_student_directory:
            canvas.drawString(A4[0] - 160, 25, 'ÖĞRENCİLER')
            canvas.linkRect('', 'students_start', Rect=(A4[0]-165, 18, A4[0]-107, 34), relative=0, thickness=0)
    canvas.restoreState()


def render_agenda_pdf(path, schedule, next_7_days, *, student_message, parent_message, extra_actions_fn=None, extra_summary_fn=None):
    """Render a real interactive PDF. Returns basic export statistics.

    Both message callbacks accept (event, day_name, display_date). No database
    writes and no network calls are performed.
    """
    font, bold = _setup_font()
    styles = _styles(font, bold)
    path = Path(path)
    if not path.parent.is_dir():
        raise FileNotFoundError(f'Kayıt klasörü bulunamadı: {path.parent}')
    if not next_7_days:
        raise ValueError('Ajanda için gün listesi boş.')
    content_width = A4[0] - 72
    story = []
    generated = _dt.datetime.now().strftime('%d.%m.%Y %H:%M')
    top = Table([[
        Paragraph('HAFTALIK AKILLI MOBİL AJANDA', styles['title'])],
        [Paragraph(f'Oluşturulma: {_safe(generated)} · YKS / LGS', styles['sub'])]
    ], colWidths=[content_width])
    top.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), BLUE),
        ('LEFTPADDING', (0, 0), (-1, -1), 15),
        ('RIGHTPADDING', (0, 0), (-1, -1), 15),
        ('TOPPADDING', (0, 0), (-1, 0), 13),
        ('BOTTOMPADDING', (0, -1), (-1, -1), 13),
    ]))
    story += [AgendaBookmark('agenda_start'), top, Spacer(1, 11)]
    # The index is generated from the same frozen schedule as the cards.
    # No extra database reads, user clicks or data changes are introduced.
    day_index_rows = []
    for date_str, day_name in next_7_days:
        try:
            short_date = _dt.date.fromisoformat(date_str).strftime('%d.%m')
        except (ValueError, TypeError):
            short_date = str(date_str)
        daily_events = schedule.get(day_name, ()) or ()
        key = 'day_' + re.sub(r'[^0-9A-Za-z_]', '_', str(date_str))
        day_index_rows.append((key, short_date, day_name,
                               sum(e.get('tip') == 'Teslim' for e in daily_events),
                               sum(e.get('tip') == 'Görüşme' for e in daily_events)))
    story.extend([AgendaDayIndex(day_index_rows, font=font, bold=bold), Spacer(1, 13)])
    student_entries, student_anchor_positions = _student_directory(schedule, next_7_days)
    if student_entries:
        story.append(AgendaBookmark('students_start'))
        # Keep each index block smaller than an A4 content frame, even with
        # thousands of students. ReportLab can paginate between these blocks.
        for start in range(0, len(student_entries), 16):
            story.append(AgendaStudentIndex(student_entries[start:start + 16],
                                            continuation=start > 0,
                                            font=font, bold=bold))
            story.append(Spacer(1, 4))
        story.append(Spacer(1, 8))
    event_count = 0
    action_count = 0
    for index_day, (date_str, day_name) in enumerate(next_7_days):
        try:
            disp_date = _dt.date.fromisoformat(date_str).strftime('%d.%m.%Y')
        except (ValueError, TypeError):
            disp_date = str(date_str)
        events = schedule.get(day_name, ()) or ()
        story.append(CondPageBreak(110))
        story.append(AgendaBookmark(day_index_rows[index_day][0], f'{day_name} {disp_date}'))
        day = Table([[Paragraph(f'{_safe(day_name)}  ·  {_safe(disp_date)}', styles['day'])]],
                    colWidths=[content_width])
        day.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#174da9')),
            ('LEFTPADDING', (0, 0), (-1, -1), 12),
            ('RIGHTPADDING', (0, 0), (-1, -1), 12),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ]))
        story += [day, Spacer(1, 9)]
        if not events:
            story += [Paragraph('Bu gün için kayıtlı ödev teslimi veya randevu yok.', styles['muted']), Spacer(1, 12)]
            continue
        for event_index, ev in enumerate(events):
            event_count += 1
            story.append(CondPageBreak(95))
            student_anchor = student_anchor_positions.get((index_day, event_index))
            if student_anchor:
                # A native bookmark at the first appearance of this student's
                # card, not a page-level approximation. No extra outline row.
                story.append(AgendaBookmark(student_anchor))
            meta = ev.get('meta') or {}
            is_deadline = ev.get('tip') == 'Teslim'
            tone = colors.HexColor('#fff5f5') if is_deadline else colors.HexColor('#eff6ff')
            badge = ((meta.get('nice_date') or disp_date) + ' · 18:00 Teslim') if is_deadline else (
                'Koçluk · ' + str(ev.get('saat') or 'Saat belirtilmedi'))
            name = Paragraph(_safe(ev.get('ad') or 'Öğrenci'), styles['student'])
            tag = Paragraph(_safe(badge), styles['badge'])
            header = Table([[name, tag]], colWidths=[content_width * .58, content_width * .42])
            header.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), tone),
                ('LINEBELOW', (0, 0), (-1, -1), .5, LINE),
                ('BOX', (0, 0), (-1, -1), .5, LINE),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                ('LEFTPADDING', (0, 0), (-1, -1), 11),
                ('TOPPADDING', (0, 0), (-1, -1), 8),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ]))
            story.extend([header, Spacer(1, 5)])
            student_phone = normalize_mobile_number(ev.get('tel_ogr'))
            parent_phone = normalize_mobile_number(ev.get('tel_veli'))
            contact = 'Öğrenci: ' + (student_phone or '—') + '    Veli: ' + (parent_phone or '—')
            if meta.get('stats'):
                contact += '    |    ' + str(meta.get('stats'))
            story.extend([Paragraph(_safe(contact), styles['muted']), Spacer(1, 5)])
            if meta.get('smart_note'):
                story.extend([Paragraph(_safe(meta['smart_note']), styles['note']), Spacer(1, 4)])
            if callable(extra_summary_fn):
                try:
                    summary_lines = extra_summary_fn(ev, day_name, disp_date) or []
                    for s_line in summary_lines:
                        if s_line:
                            story.extend([Paragraph(_safe(s_line), styles['muted']), Spacer(1, 3)])
                except Exception:
                    pass
            # Actions must be near the top of each student card on a phone.
            # One-touch actions still only open drafts/call prompts; never send.
            student_actions = []
            parent_actions = []
            direct = student_phone or parent_phone
            wa_part_count = 0
            if direct:
                msg = student_message(ev, day_name, disp_date) if student_phone else parent_message(ev, day_name, disp_date)
                wa_actions = whatsapp_actions(direct, msg,
                                              single_label='WhatsApp Raporu',
                                              multi_label='WhatsApp')
                wa_part_count += len(wa_actions)
                # Keep the call action near the first WhatsApp button, even
                # when dozens of numbered report sections follow.
                student_actions = wa_actions[:1] + [('Ara', '#ffffff', call_url(direct))] + wa_actions[1:]
            if parent_phone and parent_phone != direct:
                wa_parent = whatsapp_actions(
                    parent_phone, parent_message(ev, day_name, disp_date),
                    single_label='Veliye WhatsApp', multi_label='Veli WA')
                wa_parent = [(label, '#0d9488', uri) for label, _, uri in wa_parent]
                wa_part_count += len(wa_parent)
                parent_actions = wa_parent[:1] + [('Veliyi Ara', '#ffffff', call_url(parent_phone))] + wa_parent[1:]
            actions = student_actions + parent_actions
            if actions:
                action_count += len(actions)
                story.append(Spacer(1, 6))
                is_long = wa_part_count > (1 + bool(parent_actions))
                if is_long:
                    story.extend([Paragraph(
                        'Uzun WhatsApp raporu numaralı bölümlere ayrıldı. '
                        'Bağlantıları sırayla açıp göndermeden önce kontrol edin.',
                        styles['note']), Spacer(1, 5)])
                # Short messages keep the original compact action row. Long
                # messages have distinct student/parent groups to avoid
                # accidentally opening a parental link for a student.
                groups = ([('Öğrenci' if student_phone else 'Veli', student_actions),
                           ('Veli', parent_actions)] if is_long else [('', actions)])
                for group_name, group_actions in groups:
                    if not group_actions:
                        continue
                    if group_name:
                        story.extend([Paragraph(_safe(group_name) + ' iletişimi', styles['muted']),
                                      Spacer(1, 3)])
                    # Never put an arbitrarily large set of links in one
                    # unbreakable PDF flowable; small batches can move pages.
                    for start in range(0, len(group_actions), 6):
                        story.append(LinkButtons(group_actions[start:start + 6], font=bold))
                        if start + 6 < len(group_actions):
                            story.append(Spacer(1, 3))
                if callable(extra_actions_fn):
                    try:
                        extra_acts = extra_actions_fn(ev, day_name, disp_date, student_phone, parent_phone) or []
                        if extra_acts:
                            action_count += len(extra_acts)
                            story.append(Spacer(1, 4))
                            for start in range(0, len(extra_acts), 3):
                                story.append(LinkButtons(extra_acts[start:start + 3], font=bold))
                                if start + 3 < len(extra_acts):
                                    story.append(Spacer(1, 3))
                    except Exception:
                        pass
                story.append(Spacer(1, 9))
            else:
                story.extend([Spacer(1, 5), Paragraph('Telefon kayıtlı değil; iletişim bağlantısı eklenmedi.', styles['muted'])])
            if is_deadline:
                lines = meta.get('lines') or []
                for line in lines:
                    story.append(Paragraph('•  ' + _safe(line), styles['body']))
                if not lines:
                    story.append(Paragraph('Ödev ayrıntısı kaydedilmemiş.', styles['muted']))
            else:
                story.append(Paragraph(_safe(ev.get('detay') or 'Koçluk görüşmesi'), styles['body']))
            if meta.get('notes'):
                story.extend([Spacer(1, 4), Paragraph('Not: ' + _safe(' · '.join(map(str, meta['notes']))), styles['note'])])
            story.append(Spacer(1, 17))
    # Build atomically: never leave behind a partial/broken user-facing PDF.
    fd, tmp_path = tempfile.mkstemp(prefix='.agenda_', suffix='.pdf', dir=str(path.parent))
    os.close(fd)
    try:
        doc = SimpleDocTemplate(tmp_path, pagesize=A4, leftMargin=36, rightMargin=36,
                                topMargin=35, bottomMargin=48,
                                title='Haftalık Akıllı Mobil Ajanda', author='KoçPilot 360')
        doc.build(story,
                  onFirstPage=lambda c, d: _footer(c, d, font,
                                                   has_student_directory=bool(student_entries)),
                  onLaterPages=lambda c, d: _footer(c, d, font,
                                                    has_student_directory=bool(student_entries)))
        if Path(tmp_path).stat().st_size < 100:
            raise IOError('PDF içeriği oluşturulamadı.')
        # ReportLab writes /Link annotations with /URI actions directly into
        # this PDF. Refuse a silent export that omits even one requested link.
        # This is a structural smoke check; independent PDF readers verify
        # final link geometry in the automated tests.
        raw_pdf = Path(tmp_path).read_bytes()
        if raw_pdf.count(b'/Subtype /Link') < action_count or raw_pdf.count(b'/S /URI') < action_count:
            raise IOError('PDF iletişim bağlantıları eksik oluşturuldu; dosya kaydedilmedi.')
        os.replace(tmp_path, path)
    finally:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)
    return {'events': event_count, 'link_annotations_expected': action_count,
            'navigation_days': len(day_index_rows),
            'navigation_students': len(student_entries), 'path': str(path)}
