def get_available_years() -> List[int]:
    """Sistemde desteklenen analiz ve projeksiyon yılları."""
    return [2026, 2025, 2024]


def get_available_cities(exam_type: str) -> List[str]:
    """İlgili sınav türünde yer alan benzersiz şehir listesi."""
    data = ALL_EXAM_DATA.get(exam_type, [])
    cities = sorted({item.get("city", "") for item in data if item.get("city")})
    return ["Tüm Şehirler"] + cities


def get_available_categories(exam_type: str) -> List[str]:
    """İlgili sınav türündeki program kategorileri."""
    data = ALL_EXAM_DATA.get(exam_type, [])
    cats = sorted({item.get("category", "") for item in data if item.get("category")})
    return ["Tüm Alanlar"] + cats


def get_exam_data(
    exam_type: str,
    year: int = 2025,
    city: Optional[str] = None,
    category: Optional[str] = None,
    search: Optional[str] = None
) -> List[Dict[str, Any]]:
    """
    Belirtilen sınav türü ve yıla göre hedefleri döndürür.
    Geriye dönük %100 uyumluluk için 'tyt', 'ayt', 'net', 'puan' alanları
    seçilen yıla göre otomatik dinamik olarak doldurulur.
    """
    raw_list = ALL_EXAM_DATA.get(exam_type, [])
    res = []
    
    y_str = str(year) if year in (2024, 2025, 2026) else "2025"
    
    for item in raw_list:
        # Şehir filtresi
        if city and city not in ("Tüm Şehirler", "Hepsi", ""):
            if item.get("city") != city:
                continue
                
        # Kategori filtresi
        if category and category not in ("Tüm Alanlar", "Hepsi", ""):
            if item.get("category") != category:
                continue
                
        # Arama filtresi
        if search and search.strip():
            q = search.strip().lower()
            if q not in item["name"].lower() and q not in item.get("city", "").lower():
                continue
                
        # Kopya oluştur ve aktif yıl değerlerini varsayılan alanlara ata
        entry = dict(item)
        entry["active_year"] = int(y_str)
        
        if "YKS" in exam_type:
            entry["tyt"] = item.get(f"tyt_{y_str}", item.get("tyt_2025", 0))
            entry["ayt"] = item.get(f"ayt_{y_str}", item.get("ayt_2025", 0))
            entry["puan"] = item.get(f"puan_{y_str}", item.get("puan_2025", 0))
            entry["rank"] = item.get(f"rank_{y_str}", item.get("rank_2025", 0))
        else: # LGS
            entry["net"] = item.get(f"net_{y_str}", item.get("net_2025", 0))
            entry["puan"] = item.get(f"puan_{y_str}", item.get("puan_2025", 0))
            entry["perc"] = item.get(f"perc_{y_str}", item.get("perc_2025", 0))
            
        res.append(entry)
        
    return res
